# Box drawing and a few symbols the editor uses. Same cell, so they line up.
g('\x01', ".....", "#####", "#...#", "#...#", "#...#", "#...#", "#####")  # box
g('\x02', "..#..", "#####", "#####", "#####", "#####", "#####", "..#..")  # plus
g('\x03', "..#..", ".###.", "#####", ".###.", "..#..", "..#..", "..#..")  # chevron
g('\x04', ".#...", "###..", "###..", ".#...", ".#...", ".#...", ".#...")  # tee
g('\x05', "#...#", "#...#", "#...#", ".#.#.", ".###.", "..#..", "..#..")  # branch

GLYPH_W, GLYPH_H, CELL_W, CELL_H = 5, 7, 6, 8
FIRST, LAST = 0x20, 0x7E
EXTRA = sorted(k for k in G if not (FIRST <= ord(k) <= LAST))

def to_bytes(rows):
    # One byte per column; bit N = row N, LSB is the top row.
    out = []
    for c in range(GLYPH_W):
        v = 0
        for r in range(GLYPH_H):
            if rows[r][c] == '#':
                v |= 1 << r
        out.append(v)
    return out

def main():
    out = []
    w = out.append
    w('/* GENERATED by scripts/gen_font.py -- do not edit by hand.')
    w(' *')
    w(' * 5x7 ASCII bitmap inside a 6x8 cell, one byte per column, LSB = top row.')
    w(' * This is the fallback font: the renderer prefers a real TTF found at')
    w(' * runtime and only uses this when none is available, so the engine and')
    w(' * editor can always draw text.')
    w(' */')
    w('')
    w('#include "afndle/render/builtinfont.h"')
    w('')
    w('const uint8_t af_builtin_font_glyphs[%d][%d] = {' % (LAST - FIRST + 1, GLYPH_W))
    for cp in range(FIRST, LAST + 1):
        ch = chr(cp)
        rows = G[ch]
        b = to_bytes(rows)
        w('    {0x%02X, 0x%02X, 0x%02X, 0x%02X, 0x%02X}, /* %s */' % ((tuple(b) + (ch,))))
    w('};')
    w('')
    w('/* Extra glyphs the editor UI needs, in the private use area. */')
    w('static const uint32_t af_builtin_extra_cp[%d] = {%s};' %
      (max(len(EXTRA), 1), ', '.join('0x%02X' % ord(k) for k in EXTRA) or '0'))
    w('static const uint8_t af_builtin_extra_glyphs[%d][5] = {' % max(len(EXTRA), 1))
    for k in EXTRA:
        w('    {0x%02X, 0x%02X, 0x%02X, 0x%02X, 0x%02X}, /* 0x%02X */' %
          (tuple(to_bytes(G[k])) + (ord(k),)))
    if not EXTRA:
        w('    {0, 0, 0, 0, 0},')
    w('};')
    w('')
    w('const AfBuiltinFont af_builtin_font = {')
    w('    .glyph_w = %d, .glyph_h = %d,' % (GLYPH_W, GLYPH_H))
    w('    .cell_w = %d,  .cell_h = %d,' % (CELL_W, CELL_H))
    w('    .first_codepoint = %d, .last_codepoint = %d,' % (FIRST, LAST))
    w('    .ascii_glyphs = &af_builtin_font_glyphs[0][0],')
    w('    .extra_count = %d,' % len(EXTRA))
    w('    .extra_codepoints = af_builtin_extra_cp,')
    w('    .extra_glyphs = &af_builtin_extra_glyphs[0][0],')
    w('};')
    w('')

    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    dest = os.path.join(root, 'src', 'render', 'builtinfont.c')
    with open(dest, 'w') as f:
        f.write('\n'.join(out))
    print('wrote %s (%d glyphs)' % (dest, len(G)))

if __name__ == '__main__':
    main()
